pub const QLUT_7ALL: [f32; 128] = {
    let mut arr = [0.0f32; 128];
    let mut i = 0;
    while i < 128 {
        let val = (i << 1) | (i >> 6);
        arr[i] = (val as f32) / 255.0;
        i += 1;
    }
    arr
};
pub const QLUT_8ALL: [f32; 256] = {
    let mut arr = [0.0f32; 256];
    let mut i = 0;
    while i < 256 {
        arr[i] = (i as f32) / 255.0;
        i += 1;
    }
    arr
};

